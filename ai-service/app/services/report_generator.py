"""
Literature review Markdown report generation service.
"""
from typing import Dict, Any, Optional
from app.config import settings


class ReportGenerator:
    @staticmethod
    def generate_markdown(job_id: str, comparison_result: Dict[str, Any], paper_ids: Optional[str] = None) -> str:
        """
        Synthesize comparison results, evidence citations, and candidate research gaps into
        a publication-ready Literature Review Report in Markdown.
        """
        md = []
        md.append("# Literature Review Report")
        md.append("\n**Generated by PaperTrail AI Service**\n")
        md.append("---\n")

        # Executive Summary
        summary = comparison_result.get("summary", "Automated comparative analysis of research literature.")
        md.append("## Executive Summary\n")
        md.append(summary)
        md.append("\n")

        # Papers Included
        papers = comparison_result.get("papers", [])
        if papers:
            md.append("## Analyzed Papers\n")
            for p in papers:
                title = p.get("title", "Untitled")
                pid = p.get("paper_id")
                md.append(f"- **{title}** (ID: `{pid}`)")
            md.append("\n")

        # Comparison Matrix
        matrix = comparison_result.get("comparison_matrix", {})
        if matrix:
            md.append("## Comparative Analysis Matrix\n")
            # Headers
            pids = [p.get("paper_id") for p in papers] if papers else []
            if not pids and paper_ids:
                pids = [p.strip() for p in paper_ids.split(",")]

            if pids:
                header = "| Dimension |" + "".join([f" Paper `{pid[:8]}` |" for pid in pids])
                separator = "|:---| " + "".join(["|:--- " for _ in pids])
                md.append(header)
                md.append(separator)

                dimensions = [
                    ("research_problem", "Research Problem"),
                    ("methodology", "Methodology"),
                    ("dataset", "Dataset"),
                    ("evaluation_metrics", "Metrics"),
                    ("reported_results", "Key Results"),
                    ("limitations", "Limitations"),
                    ("future_work", "Future Work"),
                ]

                for dim_key, dim_label in dimensions:
                    row_data = matrix.get(dim_key, {})
                    row = f"| **{dim_label}** |"
                    for pid in pids:
                        val = str(row_data.get(pid, "Not reported")).replace("|", "\\|")
                        # Truncate for table clarity
                        if len(val) > 120:
                            val = val[:117] + "..."
                        row += f" {val} |"
                    md.append(row)
                md.append("\n")

        # Candidate Research Gaps
        gaps = comparison_result.get("research_gaps", [])
        if gaps:
            md.append("## Candidate Research Gaps & Open Challenges\n")
            md.append("> **Important Note:** These are algorithmically identified research gaps derived from "
                      "authors' stated limitations and future work proposals. They require manual scholarly "
                      "verification before concluding research novelty.\n")
            for g in gaps:
                md.append(f"- {g}")
            md.append("\n")

        # Grounding & Evidence References
        evidence_refs = comparison_result.get("evidence_references", [])
        if evidence_refs:
            md.append("## Traceable Evidence Quotations\n")
            for ref in evidence_refs[:15]:
                pid = ref.get("paper_id")
                page = ref.get("page_number")
                text = ref.get("text", "").replace("\n", " ").strip()
                page_str = f"Page {page}" if page else "Page not specified"
                md.append(f"> \"{text}\"\n> — **Paper `{pid}`**, {page_str}\n")

        # Uncertainty & Limitations of Review
        notes = comparison_result.get("uncertainty_notes", [])
        if notes:
            md.append("## Review Limitations & Uncertainty\n")
            for note in notes:
                md.append(f"- {note}")
            md.append("\n")

        md.append("---\n")
        md.append("*Report generated with zero generative fabrication: all cited figures and quotes strictly derive from document source text.*")

        return "\n".join(md)
