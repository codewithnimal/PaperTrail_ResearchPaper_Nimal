package com.papertrail.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.papertrail.client.AiServiceClient;
import com.papertrail.entity.ComparisonJob;
import com.papertrail.entity.ComparisonResult;
import com.papertrail.exception.ResourceNotFoundException;
import com.papertrail.repository.ComparisonJobRepository;
import com.papertrail.repository.ComparisonResultRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.util.*;

/**
 * Service for generating literature review reports from comparison results.
 */
@Service
public class ReportService {

    private static final Logger log = LoggerFactory.getLogger(ReportService.class);

    private final ComparisonJobRepository jobRepository;
    private final ComparisonResultRepository resultRepository;
    private final AiServiceClient aiServiceClient;
    private final ObjectMapper objectMapper;

    public ReportService(
            ComparisonJobRepository jobRepository,
            ComparisonResultRepository resultRepository,
            AiServiceClient aiServiceClient,
            ObjectMapper objectMapper) {
        this.jobRepository = jobRepository;
        this.resultRepository = resultRepository;
        this.aiServiceClient = aiServiceClient;
        this.objectMapper = objectMapper;
    }

    /**
     * Generate a Markdown report for a completed comparison.
     */
    public String generateMarkdownReport(UUID comparisonId) {
        ComparisonJob job = jobRepository.findById(comparisonId)
            .orElseThrow(() -> new ResourceNotFoundException("ComparisonJob", comparisonId));

        ComparisonResult result = resultRepository.findByJobId(comparisonId)
            .orElseThrow(() -> new ResourceNotFoundException(
                "No results found for comparison job " + comparisonId));

        try {
            JsonNode resultJson = objectMapper.readTree(result.getResultJson());

            // Try AI service for advanced report generation
            try {
                Map<String, Object> reportRequest = new HashMap<>();
                reportRequest.put("job_id", comparisonId.toString());
                reportRequest.put("comparison_result", objectMapper.readValue(result.getResultJson(), Map.class));
                reportRequest.put("paper_ids", job.getPaperIds());

                JsonNode reportResult = aiServiceClient.generateReport(reportRequest);
                if (reportResult.has("markdown")) {
                    return reportResult.get("markdown").asText();
                }
            } catch (Exception e) {
                log.warn("AI report generation failed, using fallback: {}", e.getMessage());
            }

            // Fallback: generate structured markdown from the comparison result
            return generateFallbackReport(job, resultJson);

        } catch (Exception e) {
            log.error("Report generation failed for comparison {}: {}", comparisonId, e.getMessage());
            throw new RuntimeException("Failed to generate report: " + e.getMessage(), e);
        }
    }

    private String generateFallbackReport(ComparisonJob job, JsonNode resultJson) {
        StringBuilder md = new StringBuilder();

        md.append("# Literature Review Report\n\n");
        md.append("**Generated by PaperTrail**\n\n");
        md.append("---\n\n");

        // Summary
        if (resultJson.has("summary")) {
            md.append("## Summary\n\n");
            md.append(resultJson.get("summary").asText("No summary available."));
            md.append("\n\n");
        }

        // Comparison question
        if (job.getComparisonQuestion() != null && !job.getComparisonQuestion().isBlank()) {
            md.append("## Research Question\n\n");
            md.append(job.getComparisonQuestion());
            md.append("\n\n");
        }

        // Papers compared
        md.append("## Papers Compared\n\n");
        String[] paperIds = job.getPaperIds().split(",");
        if (resultJson.has("papers")) {
            for (JsonNode paper : resultJson.get("papers")) {
                md.append("- **").append(paper.path("title").asText("Untitled")).append("**");
                md.append(" (ID: ").append(paper.path("paper_id").asText()).append(")\n");
            }
        } else {
            for (String pid : paperIds) {
                md.append("- Paper ID: ").append(pid.trim()).append("\n");
            }
        }
        md.append("\n");

        // Comparison matrix
        if (resultJson.has("comparison_matrix")) {
            md.append("## Comparison Matrix\n\n");
            JsonNode matrix = resultJson.get("comparison_matrix");

            // Build table from the matrix
            md.append("| Aspect |");
            for (String pid : paperIds) {
                md.append(" Paper ").append(pid.trim().substring(0, 8)).append("... |");
            }
            md.append("\n|--------|");
            for (String ignored : paperIds) {
                md.append("----------|");
            }
            md.append("\n");

            String[] aspects = {"research_problem", "methodology", "dataset", "evaluation_metrics",
                               "reported_results", "limitations", "future_work"};

            for (String aspect : aspects) {
                if (matrix.has(aspect)) {
                    md.append("| **").append(formatAspectName(aspect)).append("** |");
                    JsonNode aspectData = matrix.get(aspect);
                    for (String pid : paperIds) {
                        String value = aspectData.path(pid.trim()).asText("Not reported");
                        md.append(" ").append(truncate(value, 80)).append(" |");
                    }
                    md.append("\n");
                }
            }
            md.append("\n");
        }

        // Research gaps
        if (resultJson.has("research_gaps")) {
            md.append("## Candidate Research Gaps\n\n");
            md.append("> **Note:** These are candidate gaps identified by automated analysis. ");
            md.append("They require manual literature review to confirm as actual research gaps.\n\n");
            JsonNode gaps = resultJson.get("research_gaps");
            if (gaps.isArray()) {
                for (JsonNode gap : gaps) {
                    md.append("- ").append(gap.asText()).append("\n");
                }
            }
            md.append("\n");
        }

        // Evidence references
        if (resultJson.has("evidence_references")) {
            md.append("## Evidence References\n\n");
            JsonNode refs = resultJson.get("evidence_references");
            if (refs.isArray()) {
                for (JsonNode ref : refs) {
                    md.append("- ");
                    md.append("Paper: ").append(ref.path("paper_id").asText());
                    if (!ref.path("page_number").isNull()) {
                        md.append(", Page ").append(ref.path("page_number").asInt());
                    }
                    md.append(": \"").append(truncate(ref.path("text").asText(), 150)).append("\"");
                    md.append("\n");
                }
            }
            md.append("\n");
        }

        md.append("---\n\n");
        md.append("*This report was generated automatically by PaperTrail. ");
        md.append("All claims should be verified against the original papers.*\n");

        return md.toString();
    }

    private String formatAspectName(String aspect) {
        return aspect.replace("_", " ").substring(0, 1).toUpperCase()
            + aspect.replace("_", " ").substring(1);
    }

    private String truncate(String text, int maxLen) {
        if (text == null) return "Not reported";
        if (text.length() <= maxLen) return text;
        return text.substring(0, maxLen) + "...";
    }
}
